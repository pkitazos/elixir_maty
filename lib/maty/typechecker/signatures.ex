defmodule Maty.Typechecker.Signatures do
  @moduledoc """
  Builds Σ, the signature environment of a `Maty.Actor` module.

  Σ maps a handler's name to its handler type, and a function id
  `{module, name, arity}` to its function type.

  (todo: this comment should be moved to typechecker)
  Nothing in this module reads or writes a module attribute. The compile hooks
  do that, in two places:

    * `@on_definition` reads the ephemeral annotations of the clause
      (`@handler`, `@init_handler`, `@handler_stub`, `@spec`), deletes them,
      and appends the record made by `clause/4` to one accumulating attribute.

    * `@before_compile` reads the records back (in source order) together with
      the session types, calls `build/3`, and either reports the errors or
      stores Σ in a single attribute for `@after_compile` to put in the `Ctx`.
  """

  alias Maty.Typechecker.TypeSpecParser
  alias Maty.ST
  alias Maty.Typechecker.Error
  alias Maty.Types
  alias Maty.Types.T, as: Type

  # todo: move these to Types or import from there or something

  @type func_id :: {module(), atom(), arity()}

  @type function_type :: {:function, [Type.t()], Type.t()}

  @type handler_type ::
          {:handler, :message, ST.t()}
          | {:handler, :init, [Type.t()], ST.t()}

  @typedoc """
  Σ - Handlers are keyed by name, since a handler's name is unique in its module at any arity
  (only the module being compiled has entries for now)
  """
  @type t :: %{
          optional(Types.handler_label()) => handler_type(),
          optional(func_id()) => function_type()
        }

  @type raw_spec :: {:spec, Macro.t(), term()}

  @typedoc """
  What kind of definition a clause belongs to:

    * `:function` - a plain `def` / `defp`
    * `{:handler, :message}` / `{:handler, :init}` - a clause generated by `defhandler`
    * `:handler_stub` - the stub `defhandler` defines for referencing handlers
  """
  @type kind :: :function | {:handler, :message} | {:handler, :init} | :handler_stub

  @typedoc """
  One record per clause (`@on_definition` fires once for each).

  `specs` is empty for every clause of a function except the one its spec is written above
  """
  @type clause :: %{
          name: atom(),
          arity: arity(),
          line: non_neg_integer(),
          kind: kind(),
          specs: [raw_spec()]
        }

  @type annotations :: %{
          handler: Types.handler_label() | nil,
          init_handler: Types.handler_label() | nil,
          handler_stub: true | nil,
          spec: [raw_spec()] | nil
        }

  @typedoc """
  An error and the definition it is about or `nil` if it is about the whole module
  """
  @type located_error :: {{atom(), arity()} | nil, Error.t()}

  # figure our a nicer way to go from 3-arity func_id to 2-arity func_id

  # todo: I have like a hundred different results all over the place, eventually make them generic?
  @type result(a) :: {:ok, a} | {:error, [located_error()]}

  # -- collect

  @doc """
  The record for one clause, from what `@on_definition` knows about it.

  Decides the clause's `kind` from its annotations and keeps its specs as they are.
  """
  @spec clause(atom(), arity(), non_neg_integer(), annotations()) :: clause()
  def clause(name, arity, line, annotations) do
    kind =
      cond do
        not is_nil(annotations.handler) -> {:handler, :message}
        not is_nil(annotations.init_handler) -> {:handler, :init}
        not is_nil(annotations.handler_stub) -> :handler_stub
        true -> :function
      end

    %{
      name: name,
      arity: arity,
      line: line,
      kind: kind,
      specs: if(is_nil(annotations.spec), do: [], else: annotations.spec)
    }
  end

  # -- build

  @doc """
  Builds Σ for `module` from its clause records and its session types.

  `clauses` are in source order
  `session_types` is a map of the `@st` declarations
  """
  @spec build(module(), [clause()], %{Types.handler_label() => ST.t()}) :: result(t())
  def build(module, cs, session_types) do
    join(
      handler_signatures(module, cs, session_types),
      function_signatures(module, cs),
      &Map.merge/2
    )
    |> join_err(name_clash_errors(module, cs))
  end

  # The handler entries of Σ.
  #
  # A message handler `h` has the type `{:handler, :message, st}`, where `st` is the session type declared for `h`
  #
  # An init handler `h` has the type `{:handler, :init, arg_types, st}`,
  # where `arg_types` are the types of the first argument in each clause's spec, sorted and without duplicates.
  #
  # Errors:
  #   * a handler with no session type declared for its name
  #   * an init handler clause whose spec does not parse
  @spec handler_signatures(module(), [clause()], %{Types.handler_label() => ST.t()}) ::
          result(%{Types.handler_label() => handler_type()})
  defp handler_signatures(module, cs, session_types) do
    hs = for c <- cs, match?({:handler, _}, c.kind), do: c

    hs
    |> Enum.group_by(fn d -> d.name end)
    |> map_m(fn {h, cs} -> handler_signature(module, session_types, h, cs) end)
    |> f_map(&Map.new/1)
  end

  # The function entries of Σ.
  #
  # A function has a single type.
  # A function with no spec gets no entry and no error here, it is reported when
  # its body is checked (WF-Func). (maybe it should be reported here..)
  #
  # Errors:
  #   * more than one spec for the same function
  #   * the errors of `parse_spec/2`
  @spec function_signatures(module(), [clause()]) :: result(%{func_id() => function_type()})
  defp function_signatures(module, cs) do
    fs = for c <- cs, match?(:function, c.kind), do: c

    fs
    |> Enum.group_by(fn c -> {c.name, c.arity} end)
    # a function with no spec is skipped, WF-Func reports it (see issues.md §15)
    |> Enum.reject(fn {_, cs} -> Enum.all?(cs, fn c -> c.specs == [] end) end)
    |> map_m(fn {_, cs} -> function_signature(module, cs) end)
    |> f_map(&Map.new/1)
  end

  # The entry of one function in Σ, from all of its clauses (at least one of which has a spec)
  @spec function_signature(module(), [clause()]) :: result({func_id(), function_type()})
  defp function_signature(module, [c | _] = cs) do
    func_id = {module, c.name, c.arity}

    # the specs of all function clauses (technically allows adding the spec in between clauses)
    case Enum.flat_map(cs, fn c -> c.specs end) do
      [spec] ->
        func_id
        |> parse_spec(spec)
        |> map_err(fn e -> [localise_err(e, func_id)] end)
        |> f_map(fn ty -> {func_id, ty} end)

      specs ->
        # reported at the function's first clause
        error =
          Error.FunctionCall.wrong_number_of_specs(module, [line: c.line], {c.name, c.arity},
            expected: 1,
            got: length(specs)
          )

        {:error, [localise_err(error, func_id)]}
    end
  end

  # Parses one raw spec into the type of the function it is written above.
  #
  # Errors:
  #   * the spec's name or arity is not that of the function
  #   * an argument type does not parse (reported with its position)
  #   * the return type does not parse
  @spec parse_spec(func_id(), raw_spec()) :: {:ok, function_type()} | {:error, Error.t()}
  defp parse_spec({module, func_name, arity}, raw_spec) do
    {:spec, {:"::", meta, [{spec_name, _, args_asts}, ret_ast]}, _pos} = raw_spec

    # the errors name the function without its module
    # todo: once we go cross-module, this may have to change??
    func_id = {func_name, arity}

    with {:info, {^func_name, ^arity}} <- {:info, {spec_name, length(args_asts)}},
         {:args, {:ok, args_ty}} <- {:args, parse_spec_args(args_asts)},
         {:ret, {:ok, ret_ty}} <- {:ret, TypeSpecParser.parse(ret_ast)} do
      function_ty = {:function, args_ty, ret_ty}
      {:ok, function_ty}
    else
      {:info, spec_id} ->
        {:error,
         Error.TypeSpecification.function_spec_info_mismatch(module, meta,
           spec_id: spec_id,
           func_id: func_id
         )}

      {:args, {:error, cause, idx}} ->
        {:error,
         Error.TypeSpecification.spec_args_parse_error_at(
           module,
           meta,
           func_id,
           idx,
           args_asts,
           cause
         )}

      {:ret, {:error, cause}} ->
        {:error,
         Error.TypeSpecification.spec_return_not_well_typed(
           module,
           meta,
           spec_name,
           ret_ast,
           cause
         )}
    end
  end

  # One error for each plain function that has the name of a handler
  @spec name_clash_errors(module(), [clause()]) :: [located_error()]
  defp name_clash_errors(module, cs) do
    hs = for c <- cs, match?({:handler, _}, c.kind), do: {c.name, c.kind}
    hs = Map.new(hs)

    collisions = for c <- cs, match?(:function, c.kind), Map.has_key?(hs, c.name), do: c

    for c <- Enum.uniq_by(collisions, fn c -> {c.name, c.arity} end) do
      {:handler, handler_kind} = hs[c.name]
      func_id = {c.name, c.arity}

      # reported at the function's first clause
      error =
        Error.FrameworkUsage.handler_name_clash(module, [line: c.line], func_id, handler_kind)

      {func_id, error}
    end
  end

  # Parses a list of spec argument type ASTs left-to-right.
  #
  # Returns:
  # `{:ok, types}` in source order
  # `{:error, cause, index}` where `index` is the position of the first bad arg
  @spec parse_spec_args([Macro.t()]) ::
          {:ok, [Type.t()]} | {:error, Error.Cause.t(), non_neg_integer()}
  defp parse_spec_args(asts) do
    asts
    |> Enum.with_index()
    |> Enum.reduce_while([], fn {ast, i}, ts ->
      case TypeSpecParser.parse(ast) do
        {:ok, t} -> {:cont, [t | ts]}
        {:error, err} -> {:halt, {:error, err, i}}
      end
    end)
    |> case do
      {:error, _, _} = err -> err
      ts -> {:ok, Enum.reverse(ts)}
    end
  end

  @spec init_arg_type(module(), clause()) :: result(Type.t())
  defp init_arg_type(module, %{name: name, arity: arity, specs: [spec]}) do
    {:spec,
     {:"::", meta,
      [
        {^name, _, [arg_ast, {:maty_actor_state, _, []}, {:session_ctx, _, []}] = args_asts},
        {:no_return, _, []}
      ]}, _pos} = spec

    func_id = {name, arity}

    TypeSpecParser.parse(arg_ast)
    |> map_err(fn cause ->
      # the annotation is the first argument of the generated spec
      error =
        Error.TypeSpecification.spec_args_parse_error_at(
          module,
          meta,
          func_id,
          0,
          args_asts,
          cause
        )

      [{func_id, error}]
    end)
  end

  # The entry of handler `h` in Σ, from all of its clauses
  @spec handler_signature(
          module(),
          %{Types.handler_label() => ST.t()},
          Types.handler_label(),
          [clause()]
        ) :: result({Types.handler_label(), handler_type()})
  defp handler_signature(module, session_types, h, cs) do
    with {:ok, st} <- fetch_st(module, session_types, cs),
         {:ok, ty} <- handler_type(module, st, cs) do
      {:ok, {h, ty}}
    end
  end

  # The session type declared for a handler's name
  # A handler with none is reported at its first clause
  @spec fetch_st(module(), %{Types.handler_label() => ST.t()}, [clause()]) :: result(ST.t())
  defp fetch_st(module, session_types, [%{name: h, arity: arity, line: line} | _]) do
    case Map.fetch(session_types, h) do
      {:ok, st} ->
        {:ok, st}

      :error ->
        {:error, [{{h, arity}, Error.ProtocolViolation.missing_handler(module, h, line: line)}]}
    end
  end

  @spec handler_type(module(), ST.t(), [clause()]) :: result(handler_type())
  # the type of a message handler only depends on its name
  defp handler_type(_, st, [%{kind: {:handler, :message}} | _]),
    do: {:ok, {:handler, :message, st}}

  defp handler_type(module, st, clauses) do
    clauses
    |> map_m(&init_arg_type(module, &1))
    |> f_map(fn tys -> {:handler, :init, Enum.sort(tys) |> Enum.dedup(), st} end)
  end

  # todo: better names for all these
  # also see other comment about generic lib

  @spec map_err({:error, a} | {:ok, term()}, (a -> b)) :: result(b) when a: var, b: var
  defp map_err({:error, err}, f), do: {:error, f.(err)}
  defp map_err({:ok, _} = ok, _), do: ok

  @spec f_map(result(a), (a -> b)) :: result(b) when a: var, b: var
  defp f_map({:ok, a}, f), do: {:ok, f.(a)}
  defp f_map({:error, _} = e, _), do: e

  # as far as I can tell this is similar to `liftA2` in haskell
  @spec join(result(a), result(b), (a, b -> c)) :: result(c) when a: var, b: var, c: var
  defp join({:ok, a}, {:ok, b}, f), do: {:ok, f.(a, b)}
  defp join({:error, err}, {:ok, _}, _), do: {:error, err}
  defp join({:ok, _}, {:error, err}, _), do: {:error, err}
  defp join({:error, a}, {:error, b}, _), do: {:error, a ++ b}

  @spec join_err(result(a), [located_error()]) :: result(a) when a: var
  defp join_err(res, []), do: res
  defp join_err({:ok, _}, errs), do: {:error, errs}
  defp join_err({:error, es}, errs), do: {:error, es ++ errs}

  @spec map_m([a], (a -> result(b))) :: result([b]) when a: var, b: var
  defp map_m(xs, f) do
    {oks, errs} = xs |> Enum.map(f) |> Enum.split_with(&match?({:ok, _}, &1))

    case errs do
      [] -> {:ok, Enum.map(oks, fn {:ok, v} -> v end)}
      _ -> {:error, Enum.flat_map(errs, fn {:error, e} -> e end)}
    end
  end

  @spec localise_err(Error.t(), func_id() | nil) :: located_error()
  defp localise_err(e, {_mod, name, arity}), do: {{name, arity}, e}
end
